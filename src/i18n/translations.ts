export type TranslationKey = keyof typeof translations.fa;

export function formatNumerals(input: string | number, mode: NumeralMode): string {
  const str = String(input);
  if (mode === 'en') {
    return str.replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)));
  }
  return str.replace(/[0-9]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]);
}

export function getTranslator(lang: Language) {
  return (key: TranslationKey): string => translations[lang][key] ?? translations.en[key];
}
